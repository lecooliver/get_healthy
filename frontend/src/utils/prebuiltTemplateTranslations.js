export const translatePrebuiltText = (value) => {
  if (typeof value !== 'string') return value
  if (translations[value]) return translations[value]

  const suffixIndex = value.lastIndexOf(' - ')
  if (suffixIndex > 0) {
    const translatedPrefix = translations[value.slice(0, suffixIndex)]
    if (translatedPrefix) return `${translatedPrefix}${value.slice(suffixIndex)}`
  }

  return value
}